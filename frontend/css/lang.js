// Rates (Mocked for Demo)
const currencyRates = {
  "uah": 1,
  "usd": 0.024, // 1 UAH = 0.024 USD
  "eur": 0.022  // 1 UAH = 0.022 EUR
};

const currencySymbols = {
  "uah": "₴",
  "usd": "$",
  "eur": "€"
};

// We store the original Ukrainian texts on elements to allow switching back.
// To do this simply, we'll keep a Map of DOM nodes to their original text, 
// OR we can just generate a reverse dictionary for EN -> UA dynamically, but that's error prone if values match.
// Instead, let's inject original text as a data attribute on first run.

function applyLanguage(lang) {
  localStorage.setItem('language', lang);
  
  // Update button UI
  const languageBtn = document.querySelector('.language-btn');
  if (languageBtn) {
    languageBtn.innerHTML = `${lang.toUpperCase()} <i class="fa-solid fa-chevron-down" style="font-size: 10px; margin-left: 4px;"></i>`;
  }
  
  // Highlight correct option
  document.querySelectorAll('.lang-option').forEach(opt => {
    opt.classList.remove('active');
    if (opt.textContent.startsWith(lang.toUpperCase())) {
      opt.classList.add('active');
    }
  });

  walkAndTranslate(document.body, lang);
  applyCurrency();
  
  // Додано: Повідомляємо інші скрипти (наприклад, events.js), що мова змінилася
  window.dispatchEvent(new Event('languageChanged'));
}

function applyCurrency() {
  const currency = localStorage.getItem('currency') || 'uah';
  const rate = currencyRates[currency];
  const symbol = currencySymbols[currency];

  // Update all elements that have a price (based on our map.js and others patterns)
  // We'll look for specific patterns or data attributes if we had them, 
  // but let's target the common UI patterns found in the project.

  // 1. Map Tooltip Prices, General spans, and button prices
  const priceElements = document.querySelectorAll('.event-info-row span, .ticket-info span, .created-event-details p span, .hotel-price, .event-card span, .buy-ticket-main-btn, .event-info p, .event-info div');
  
  priceElements.forEach(el => {
    // If element has children that might be prices, we handle them individually or skip
    // But for simple cases like <p>500 UAH</p> it works.
    const text = el.textContent.trim();
    
    // Match "123 ₴" or "123 грн" or "123 UAH" or "UAH 123"
    const priceMatch = text.match(/(\d+)\s*(₴|грн|UAH)|(₴|грн|UAH)\s*(\d+)/i);
    if (priceMatch) {
      // Find which group matched the number and currency
      const num = priceMatch[1] || priceMatch[4];
      const cur = priceMatch[2] || priceMatch[3];
      const fullMatch = priceMatch[0];

      if (!el.hasAttribute('data-orig-price')) {
        el.setAttribute('data-orig-price', num);
        el.setAttribute('data-orig-full-text', text);
      }
      const origPrice = parseFloat(el.getAttribute('data-orig-price'));
      const origFullText = el.getAttribute('data-orig-full-text');
      const converted = (origPrice * rate).toFixed(0);
      
      const newPriceText = `${converted} ${symbol}`;
      el.textContent = origFullText.replace(fullMatch, newPriceText);
    }
  });

  // Specifically for hotel cards if they don't use span
  const hotelLinks = document.querySelectorAll('.hotel-link'); // Just a hook to find cards
  // Hotel cards are complex, let's just use the generic walker for simplicity if needed, 
  // but the above selector should catch most.
}

function setCurrency(cur) {
  localStorage.setItem('currency', cur);
  applyCurrency();
}

function walkAndTranslate(node, targetLang) {
  // Translate Placeholders
  if (node.nodeType === 1) { // Element node
    // Skip scripts, styles, etc.
    if (['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(node.tagName)) return;

    if (node.hasAttribute('placeholder')) {
      if (!node.hasAttribute('data-orig-placeholder')) {
        node.setAttribute('data-orig-placeholder', node.getAttribute('placeholder').trim());
      }
      const origText = node.getAttribute('data-orig-placeholder');
      if (targetLang === 'en' && translations.en[origText]) {
        node.setAttribute('placeholder', translations.en[origText]);
      } else if (targetLang === 'ua') {
        node.setAttribute('placeholder', origText);
      }
    }
    
    // Also translate specific input value if it's a button
    if (node.tagName === 'INPUT' && (node.type === 'button' || node.type === 'submit')) {
      if (!node.hasAttribute('data-orig-value')) {
        node.setAttribute('data-orig-value', node.value.trim());
      }
      const origText = node.getAttribute('data-orig-value');
      if (targetLang === 'en' && translations.en[origText]) {
        node.value = translations.en[origText];
      } else if (targetLang === 'ua') {
        node.value = origText;
      }
    }

    // Traverse children
    node.childNodes.forEach(child => walkAndTranslate(child, targetLang));
  } else if (node.nodeType === 3) { // Text node
    const trimmed = node.nodeValue.trim();
    if (!trimmed) return;

    // Store original text
    if (!node.parentElement.hasAttribute('data-orig-text')) {
      // Because a parent can have multiple text nodes, we might overwrite. 
      // To be safe, we just store it in an array or map, but for simplicity we can just replace text node directly if we attach a property to the DOM node.
      if (node._origText === undefined) {
        node._origText = trimmed;
      }
    }
    
    const origText = node._origText || trimmed;
    
    if (targetLang === 'en' && translations.en[origText]) {
      node.nodeValue = node.nodeValue.replace(trimmed, translations.en[origText]);
    } else if (targetLang === 'ua' && node._origText) {
      node.nodeValue = node.nodeValue.replace(trimmed, node._origText);
    }
  }
}

// Initialize on page load
document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('language') || 'ua';
  applyLanguage(savedLang);
});
